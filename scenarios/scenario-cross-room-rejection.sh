#!/usr/bin/env bash
# =============================================================================
# Scenario: cross-room-rejection
#
# #lab-other is mapped NOWHERE (deliberate rig choice, documented in
# scenarios/README.md): the relays are members so events reach them, but the
# room is outside every matrix_rooms mapping. Nothing sent there may trigger
# a radio send - including a reply referencing an event that IS mapped in
# #lab-bridge and a reaction to it.
#
# Assertions (state/API only), per event: ordinary text, a reply referencing
# an event that IS mapped in #lab-bridge, and a reaction to an in-room event,
# all sent by the driver user in #lab-other (the homeserver itself rejects
# cross-room m.relation reactions with 400 M_UNKNOWN "Relations must be in
# the same room", so only the in-room reaction is sendable at all):
#   1. No message_map row keyed by any of those exact event ids in relay A or
#      relay B (a radio send would have written one after the confirmed send).
#   2. No relay-authored room event in #lab-bridge carries those events'
#      markers (nothing was re-relayed).
#   3. The total message_map row count in each relay is unchanged from the
#      pre-act baseline (no radio traffic at all was generated by the act).
# =============================================================================
set -euo pipefail
# shellcheck source=lib/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

require_rig
resolve_rooms

[[ -n ${ROOM_OTHER_ID} ]] ||
	SC_SKIP "#lab-other not provisioned (runtime.json lacks lab-other)"

SCENARIO="cross-room-rejection"
MARKER_TEXT="OTHER-TEXT-$(SC_UID)"
MARKER_REPLY="OTHER-REPLY-$(SC_UID)"
MARKER_SEED="OTHER-SEED-$(SC_UID)"
SINCE_MS="$(date +%s%3N)"

# --- Baseline: a mapped event (from the AlphaLab peer) to reply/react to -------
capture out lib_py radio.py send-text "${NODE_A_PEER_HOST}" "${NODE_A_PEER_PORT}" "${MARKER_SEED}"
((SC_STATUS == 0)) || SC_FAIL "seed radio injection failed" "${out}"
capture seed_json lib_py mx_events.py wait "${ROOM_ALPHA_CH0_ID}" \
	--sender "${BOT_A_MXID}" --body-contains "${MARKER_SEED}" \
	--require-envelope --since-ms "${SINCE_MS}" --timeout "${MATRIX_WAIT_SECONDS}"
((SC_STATUS == 0)) || SC_FAIL "no canonical seed event in the bridge room" "${seed_json}"
SEED_EVENT_ID="$(jq_get "${seed_json}" event.event_id | tr -d '"')"

# Relay B bridges the seed onto its own radio asynchronously; its map row
# lands seconds after the Matrix event. Wait for it before baselining, or
# the late bridge row looks like act-generated radio traffic.
capture out lib_py maps.py rows-for-event "${MAP_DB_B}" "${SEED_EVENT_ID}" --wait "${RADIO_WAIT_SECONDS}"
((SC_STATUS == 0)) || SC_FAIL "relay B did not bridge the seed event" "${out}"

capture count_a lib_py maps.py count "${MAP_DB_A}"
capture count_b lib_py maps.py count "${MAP_DB_B}"
BASELINE_A=$(jq_get "${count_a}" count | tr -d '"')
BASELINE_B=$(jq_get "${count_b}" count | tr -d '"')
SC_PASS "baseline captured" "seed_event=${SEED_EVENT_ID} map_rows A=${BASELINE_A} B=${BASELINE_B}"

# --- Act: three events in the unmapped room -----------------------------------
DRIVER_TOKEN="$(lib_py lab_env_probe.py driver_token | tr -d '"')"
capture out tools_exec python3 - <<PYEOF
import json, sys
sys.path.insert(0, "${SCENARIOS_LIB_DIR}")
from lab_env import send_message, send_reaction, driver_token
room = "${ROOM_OTHER_ID}"
seed = "${SEED_EVENT_ID}"
text_event = send_message(driver_token(), room, "${MARKER_TEXT}")
# The reply keeps the cross-room reference: the relays must refuse to
# resolve it just because the target is mapped. The reaction must target
# an in-room event - Synapse rejects cross-room m.relation annotations
# server-side, so that combination is unsendable by construction.
reply_event = send_message(driver_token(), room, "${MARKER_REPLY}", reply_to=seed)
reaction_event = send_reaction(driver_token(), room, text_event, "🌀")
print(json.dumps({"text": text_event, "reply": reply_event, "reaction": reaction_event}))
PYEOF
((SC_STATUS == 0)) || SC_FAIL "unmapped-room events not sent" "${out}"
EVENT_TEXT_ID=$(jq_get "${out}" text | tr -d '"')
EVENT_REPLY_ID=$(jq_get "${out}" reply | tr -d '"')
EVENT_REACTION_ID=$(jq_get "${out}" reaction | tr -d '"')
SC_PASS "sent text/reply/reaction into the unmapped room" \
	"text=${EVENT_TEXT_ID} reply=${EVENT_REPLY_ID} reaction=${EVENT_REACTION_ID}"

sleep "${SETTLE_SECONDS}"

# --- Assertion 1: no map rows for the exact event ids ---------------------------
for event_id in "${EVENT_TEXT_ID}" "${EVENT_REPLY_ID}" "${EVENT_REACTION_ID}"; do
	for side in A B; do
		db_var="MAP_DB_${side}"
		capture rows lib_py maps.py rows-for-event "${!db_var}" "${event_id}"
		row_count=$(jq_get "${rows}" 'rows' | grep -c '"meshtastic_id"' || true)
		((row_count == 0)) ||
			SC_FAIL "[${side}] event ${event_id} produced a map row (radio send triggered)" "${rows}"
	done
done
SC_PASS "no map rows for any #lab-other event id in either relay"

# --- Assertion 2: nothing re-relayed into the bridge room ------------------------
for marker in "${MARKER_TEXT}" "${MARKER_REPLY}"; do
	for bot in "${BOT_A_MXID}" "${BOT_B_MXID}"; do
		capture out lib_py mx_events.py scan "${ROOM_ALPHA_CH0_ID}" \
			--since-ms "${SINCE_MS}" --sender "${bot}" --body-contains "${marker}"
		hits=$(jq_get "${out}" 'matches' | grep -c '"event_id"' || true)
		((hits == 0)) ||
			SC_FAIL "relay ${bot} re-relayed unmapped-room content into #lab-alpha-ch0" "${out}"
	done
done
SC_PASS "no relay-authored room event carries the unmapped-room markers"

# --- Assertion 3: total map rows unchanged ---------------------------------------
sleep "${SETTLE_SECONDS}"
capture count_a lib_py maps.py count "${MAP_DB_A}"
capture count_b lib_py maps.py count "${MAP_DB_B}"
FINAL_A=$(jq_get "${count_a}" count | tr -d '"')
FINAL_B=$(jq_get "${count_b}" count | tr -d '"')
((FINAL_A == BASELINE_A)) ||
	SC_FAIL "relay A map grew during the unmapped-room act (radio traffic occurred)" \
		"baseline=${BASELINE_A} final=${FINAL_A}"
((FINAL_B == BASELINE_B)) ||
	SC_FAIL "relay B map grew during the unmapped-room act (radio traffic occurred)" \
		"baseline=${BASELINE_B} final=${FINAL_B}"
SC_PASS "message_map row counts unchanged (no radio traffic for those event ids)" \
	"A: ${BASELINE_A} -> ${FINAL_A}, B: ${BASELINE_B} -> ${FINAL_B}"

SC_LOG "[$SCENARIO] complete"
