"""Named, committed rig configurations: the preset library.

WHY THIS EXISTS
---------------
A known-good rig configuration is picked from a library, not rebuilt by
hand and not overwritten by the next bring-up. A preset records the
CHOICES a rig configuration is made of -- the full source pin map (the
``sources.lock.json`` schema), the topology the rig is brought up as, and
the suite that runs against it -- as one committed JSON file in
``lab/presets/<name>.json``.

It deliberately records nothing else. Tokens, PSKs and room ids rotate on
every provision and live in private state (``lab/state/``,
``lab/config/meshnet.env``); manifests, ``.env`` and ``scenario.env`` are
deterministic given pins + topology and are regenerated by ``docker
prepare`` and ``lab/up.sh`` exactly as before. Loading a preset therefore
cannot leak or stale-copy a secret: it re-derives everything from the
recorded choices.

Distinct presets may share the same pin set -- they differ in topology,
suite or intent -- so a preset is identified by membership, not by
uniqueness of its pins: the library must record the pin set of the
current lock, and the lock may equal any saved preset's pins.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import re
import subprocess
from pathlib import Path

from . import docker as rig

PRESET_FIELDS = ("name", "description", "topology", "sources", "suite")

# The topology vocabulary is the docker-up profile set; each topology
# maps to the lab/up.sh flag the bring-up runs with (base passes none).
TOPOLOGIES = ("base", "normal", "stress", "openhop", "openhop-radio")
UP_FLAGS = {
    "base": (),
    "normal": ("--normal",),
    "stress": ("--with-medre",),
    "openhop": ("--openhop",),
    "openhop-radio": ("--openhop-radio",),
}

NAME_RE = re.compile(r"[a-z0-9][a-z0-9-]*")

# Suite entry vocabulary. ``scenarios`` is the compose scenario suite via
# lab/run-scenarios.sh; ``scenario:<name>`` is one scenario script;
# ``qual:<stage>`` is one stage of the openHop qualification driver
# (lab/tools/openhop_qualify.py), which sequences its own up/down
# transitions across the openHop topologies.
SUITE_RUNNER_ENTRY = "scenarios"
SCENARIO_PREFIX = "scenario:"
QUAL_PREFIX = "qual:"


def presets_dir(root: Path) -> Path:
    return Path(root) / "lab" / "presets"


def preset_path(root: Path, name: str) -> Path:
    return presets_dir(root) / f"{name}.json"


def qualify_stage_names(root: Path) -> tuple[str, ...]:
    """The stages lab/tools/openhop_qualify.py drives, in its own order.

    Derived from the driver itself (never copied), so the vocabulary
    cannot drift from what the driver actually runs. Loading the module
    is pure: it defines constants and a generator, it starts nothing.
    """
    path = Path(root) / "lab" / "tools" / "openhop_qualify.py"
    spec = importlib.util.spec_from_file_location("lab_openhop_qualify", path)
    if spec is None or spec.loader is None:
        raise ValueError(f"cannot load the qualification driver at {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return tuple(name for name, _ in module.stages(Path(root) / "lab" / "state", False))


def validate_suite(root: Path, suite) -> None:
    """Every suite entry must reference a script or stage that exists."""
    if not isinstance(suite, list) or not suite:
        raise ValueError("the suite must be a non-empty list of entries")
    seen = set()
    for entry in suite:
        if not isinstance(entry, str) or not entry:
            raise ValueError(f"suite entry {entry!r} must be a non-empty string")
        if entry in seen:
            raise ValueError(f"suite entry {entry!r} is listed more than once")
        seen.add(entry)
        if entry == SUITE_RUNNER_ENTRY:
            if not (Path(root) / "lab" / "run-scenarios.sh").is_file():
                raise ValueError(
                    f"suite entry {entry!r}: lab/run-scenarios.sh is missing"
                )
        elif entry.startswith(SCENARIO_PREFIX):
            name = entry[len(SCENARIO_PREFIX) :]
            if not (Path(root) / "scenarios" / f"scenario-{name}.sh").is_file():
                raise ValueError(
                    f"suite entry {entry!r}: scenarios/scenario-{name}.sh does not exist"
                )
        elif entry.startswith(QUAL_PREFIX):
            stage = entry[len(QUAL_PREFIX) :]
            if stage not in qualify_stage_names(root):
                raise ValueError(
                    f"suite entry {entry!r} is not a stage of "
                    "lab/tools/openhop_qualify.py"
                )
        else:
            raise ValueError(
                f"suite entry {entry!r} must be {SUITE_RUNNER_ENTRY!r}, "
                f"'{SCENARIO_PREFIX}<name>' or '{QUAL_PREFIX}<stage>'"
            )


def validate_preset(root: Path, data, expected_name: str) -> dict:
    """Structural validation of one preset record (raises ValueError)."""
    if not isinstance(data, dict) or set(data) != set(PRESET_FIELDS):
        raise ValueError(
            f"a preset records exactly {', '.join(PRESET_FIELDS)} "
            f"(got {sorted(data) if isinstance(data, dict) else type(data).__name__})"
        )
    name = data["name"]
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise ValueError(
            f"preset name {name!r} must match {NAME_RE.pattern} "
            "(it names lab/presets/<name>.json)"
        )
    if name != expected_name:
        raise ValueError(
            f"preset name {name!r} does not match its file name {expected_name!r}"
        )
    description = data["description"]
    if (
        not isinstance(description, str)
        or not description.strip()
        or "\n" in description
    ):
        raise ValueError("the description must be one non-empty line")
    if data["topology"] not in TOPOLOGIES:
        raise ValueError(
            f"topology {data['topology']!r} must be one of: {', '.join(TOPOLOGIES)}"
        )
    sources = data["sources"]
    if not isinstance(sources, dict) or set(sources) != set(rig.SOURCES):
        raise ValueError(
            "a preset records the full ten-entry source pin map "
            "(the sources.lock.json schema)"
        )
    for key, entry in sources.items():
        if set(entry) != {"url", "ref"} or not re.fullmatch(
            r"[0-9a-f]{40}", entry["ref"]
        ):
            raise ValueError(f"{key}: exact full commit SHA required")
        if not rig.SOURCE_URL_RE.fullmatch(entry["url"]):
            raise ValueError(
                f"{key}: source URLs must be public HTTPS GitHub URLs without credentials"
            )
    validate_suite(root, data["suite"])
    return data


def read_preset(root: Path, name: str) -> dict:
    """Load and validate one preset by name."""
    path = preset_path(root, name)
    if not path.is_file():
        available = ", ".join(p.stem for p in sorted(presets_dir(root).glob("*.json")))
        raise ValueError(
            f"no preset named {name!r} in {presets_dir(root)} "
            f"(saved presets: {available or 'none'})"
        )
    return _read_preset_file(root, path)


def _read_preset_file(root: Path, path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise ValueError(f"{path}: invalid JSON ({exc})") from exc
    return validate_preset(root, data, path.stem)


def load_library(root: Path) -> list[dict]:
    """Every preset file in lab/presets/, structurally validated.

    An empty (or missing) preset library is a failure, never a vacuous
    pass: the library exists to be picked from.
    """
    paths = sorted(presets_dir(root).glob("*.json"))
    if not paths:
        raise ValueError(
            f"{presets_dir(root)}: the preset library is empty; "
            "save or seed a preset first"
        )
    return [_read_preset_file(root, path) for path in paths]


def validate_preset_library(root: Path) -> list[dict]:
    """The library is non-empty, structurally valid, and records the lock.

    The lock's pin set must equal AT LEAST ONE preset's pin set --
    membership, not uniqueness: distinct presets may legitimately share
    pins (they differ in topology, suite or intent).
    """
    library = load_library(root)
    pins = rig.lock(root)
    if not any(preset["sources"] == pins for preset in library):
        raise ValueError(
            "no preset records the current sources.lock.json pin set; "
            "save the current configuration first"
        )
    return library


